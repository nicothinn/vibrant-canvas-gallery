const Catalog = () => {
  const [selectedCategory, setSelectedCategory] = useState<CatalogCategory | null>(null);
  const [currentImageIndex, setCurrentImageIndex] = useState(0);
  const [lightboxImage, setLightboxImage] = useState<string | null>(null);

  const openCategory = (cat: CatalogCategory) => {
    setSelectedCategory(cat);
    setCurrentImageIndex(0);
  };

  const goNext = () => {
    if (!selectedCategory) return;
    setCurrentImageIndex(prev => (prev + 1) % selectedCategory.images.length);
  };

  const goPrev = () => {
    if (!selectedCategory) return;
    setCurrentImageIndex(prev => (prev - 1 + selectedCategory.images.length) % selectedCategory.images.length);
  };

  // Navegación con teclado
  useEffect(() => {
    const handleKey = (e: KeyboardEvent) => {
      if (!selectedCategory) return;
      if (e.key === 'ArrowRight') goNext();
      if (e.key === 'ArrowLeft') goPrev();
    };
    window.addEventListener('keydown', handleKey);
    return () => window.removeEventListener('keydown', handleKey);
  }, [selectedCategory]);

  return (
    <section id="catalog" className="py-20 bg-white">
      <div className="container mx-auto px-4">
        <div className="text-center mb-12">
          <h2 className="text-3xl md:text-4xl font-playfair font-bold mb-4">Catálogo</h2>
          <p className="text-gray-600 max-w-2xl mx-auto font-montserrat">
            Explora nuestras colecciones de arte: ropa pintada a mano, cuadros originales y muebles decorados.
          </p>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-8 max-w-4xl mx-auto">
          {categories.map((cat) => (
            <button
              key={cat.id}
              onClick={() => openCategory(cat)}
              className="group relative overflow-hidden rounded-2xl shadow-lg hover:shadow-xl transition-all duration-300 aspect-square"
            >
              <img
                src={cat.coverImage}
                alt={cat.name}
                className="w-full h-full object-cover group-hover:scale-110 transition-transform duration-500"
              />
              <div className="absolute inset-0 bg-black/30 group-hover:bg-black/50 transition-colors duration-300 flex items-end justify-center pb-8">
                <span className="text-white font-playfair text-2xl font-bold tracking-wide drop-shadow-lg">
                  {cat.name}
                </span>
              </div>
            </button>
          ))}
        </div>
      </div>

      {/* Modal / Popup de galería */}
      <Dialog open={!!selectedCategory} onOpenChange={() => setSelectedCategory(null)}>
        <DialogContent className="sm:max-w-4xl max-h-[90vh] overflow-y-auto">
          {selectedCategory && (
            <>
              <DialogHeader>
                <DialogTitle className="text-2xl font-playfair">{selectedCategory.name}</DialogTitle>
              </DialogHeader>

              <div className="mt-4">
                {/* Imagen principal */}
                <div
                  className="relative h-80 md:h-96 rounded-lg overflow-hidden mb-4 cursor-pointer"
                  onClick={() => setLightboxImage(selectedCategory.images[currentImageIndex])}
                >
                  <img
                    src={selectedCategory.images[currentImageIndex]}
                    alt={`${selectedCategory.name} ${currentImageIndex + 1}`}
                    className="w-full h-full object-contain bg-gray-100 hover:opacity-90 transition-opacity"
                    loading="eager"
                  />
                  <button
                    onClick={goPrev}
                    className="absolute left-2 top-1/2 -translate-y-1/2 bg-black/40 hover:bg-black/60 text-white rounded-full p-2 transition-colors"
                  >
                    <ChevronLeft size={20} />
                  </button>
                  <button
                    onClick={goNext}
                    className="absolute right-2 top-1/2 -translate-y-1/2 bg-black/40 hover:bg-black/60 text-white rounded-full p-2 transition-colors"
                  >
                    <ChevronRight size={20} />
                  </button>
                  <div className="absolute bottom-2 right-3 bg-black/50 text-white text-sm px-3 py-1 rounded-full font-montserrat">
                    {currentImageIndex + 1} / {selectedCategory.images.length}
                  </div>
                </div>

                {/* Miniaturas — solo mostrar las cercanas a la imagen actual */}
                <div className="flex gap-2 overflow-x-auto pb-2 scrollbar-none justify-center" style={{ scrollbarWidth: 'none' }}>
                  {selectedCategory.images.map((img, i) => {
                    const dist = Math.abs(i - currentImageIndex);
                    if (dist > 5 && i !== 0 && i !== selectedCategory.images.length - 1) return null;
                    return (
                      <button
                        key={i}
                        onClick={() => setCurrentImageIndex(i)}
                        className={`flex-shrink-0 w-14 h-14 rounded-md overflow-hidden border-2 transition-all ${
                          i === currentImageIndex ? 'border-primary scale-110' : 'border-transparent hover:border-gray-300 opacity-60'
                        }`}
                      >
                        <img src={img} alt="" className="w-full h-full object-cover" loading="lazy" />
                      </button>
                    );
                  })}
                </div>
              </div>
            </>
          )}
        </DialogContent>
      </Dialog>

      {/* Lightbox - imagen a pantalla completa */}
      {lightboxImage && (
        <div
          className="fixed inset-0 z-[100] bg-black/90 flex items-center justify-center cursor-pointer"
          onClick={() => setLightboxImage(null)}
        >
          <img
            src={lightboxImage}
            alt="Imagen completa"
            className="max-w-[95vw] max-h-[95vh] object-contain"
          />
          <button
            onClick={(e) => { e.stopPropagation(); setLightboxImage(null); }}
            className="absolute top-4 right-4 text-white bg-black/50 hover:bg-black/70 rounded-full w-10 h-10 flex items-center justify-center text-xl"
          >
            ×
          </button>
        </div>
      )}
    </section>
  );
};

export default Catalog;
